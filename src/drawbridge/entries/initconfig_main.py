_EMPTY_ENV_TEMPLATE = """\\
# Drawbridge compose interpolation pin — DELIBERATELY EMPTY (plan D13).
# Passed as --env-file on every compose invocation so no project-directory
# .env is ever loaded implicitly; business secrets belong in the admin
# template's env_file: directives.
"""


def _default_source_config_dir() -> Path | None:
    candidate = Path(__file__).resolve().parents[3] / "configs"
    if (candidate / "operations.yaml").is_file():
        return candidate
    return None


def init_config(
    target_dir: Path,
    *,
    root: Path,
    host: str,
    port: int,
    cidr: str,
    source_config_dir: Path,
) -> list[Path]:
    """Write the skeleton; returns the created files in order."""
    files = {
        "drawbridge.yaml": _MAIN_TEMPLATE.format(
            root=root.as_posix(), host=host, port=port, cidr=cidr
        ),
        "apps.yaml": _APPS_TEMPLATE.format(root=root.as_posix()),
    }
    existing = [
        name
        for name in (*files, "operations.yaml", "workflows.yaml")
        if (target_dir / name).exists()
    ]
    if existing:
        raise FileExistsError(
            f"refusing to overwrite existing files in {target_dir}: {existing}; "
            "choose a fresh directory"
        )
    target_dir.mkdir(parents=True, exist_ok=True)
    created: list[Path] = []
    for name in ("operations.yaml", "workflows.yaml"):
        destination = target_dir / name
        shutil.copyfile(source_config_dir / name, destination)
        created.append(destination)
    for name, content in files.items():
        destination = target_dir / name
        destination.write_text(content, encoding="utf-8")
        created.append(destination)
    compose_dir = target_dir / "compose"
    compose_dir.mkdir(exist_ok=True)
    compose = compose_dir / "demo.staging.yaml"
    compose.write_text(_COMPOSE_TEMPLATE, encoding="utf-8")
    created.append(compose)
    empty_env = compose_dir / "empty.env"
    empty_env.write_text(_EMPTY_ENV_TEMPLATE, encoding="utf-8")
    created.append(empty_env)
    return created


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="drawbridge-init-config",
        description="Generate a deployment configuration skeleton (four YAMLs + compose template).",
    )
    parser.add_argument("target_dir", type=Path, help="directory to create the bundle in")
    parser.add_argument(
        "--root",
        type=Path,
        required=True,
        help="deployment root the generated paths anchor to (e.g. /srv/drawbridge)",
    )
    parser.add_argument("--host", default="192.168.18.7", help="server address clients use")
    parser.add_argument("--port", type=int, default=8787)
    parser.add_argument("--cidr", default="192.168.0.0/16", help="client source allowlist")
    parser.add_argument(
        "--source-config-dir",
        default=None,
        help="bundle to copy operations/workflows from (default: repository configs/)",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_arg_parser().parse_args(argv)
    source = (
        Path(args.source_config_dir) if args.source_config_dir else _default_source_config_dir()
    )
    if source is None or not (source / "operations.yaml").is_file():
        print(
            "cannot locate a source config bundle; pass --source-config-dir or "
            "run from the repository",
            file=sys.stderr,
        )
        return 2
    try:
        created = init_config(
            args.target_dir,
            root=args.root,
            host=args.host,
            port=args.port,
            cidr=args.cidr,
            source_config_dir=source,
        )
    except FileExistsError as exc:
        print(str(exc), file=sys.stderr)
        return 3
    except OSError as exc:
        print(f"cannot write the bundle: {exc}", file=sys.stderr)
        return 1
    for path in created:
        print(path)
    print(*_REPLACE_HINTS, sep="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
