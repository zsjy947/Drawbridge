"""drawbridge-init-config: generate a deployment configuration skeleton.

Borrowed from the reference implementation's bootstrap command, adapted to
this repository's four-file bundle: copies the repository's operation and
workflow catalogs verbatim (they are code-coupled and reviewed together)
and generates ``drawbridge.yaml`` / ``apps.yaml`` / the Compose template
anchored at an operator-supplied root directory, with explicit
``REPLACE_*`` placeholders for the values only the administrator knows
(repo origin, BuildKit socket, frozen test image id).

Idempotence: refuses to overwrite any existing file in the target
directory — regeneration means a new directory.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

_REPLACE_HINTS = (
    "Manual steps before first use:",
    "1. apps.yaml: set git.repo_path to the pre-cloned repository and git.origin",
    "   to its real origin URL (local mirror or ssh/https).",
    "2. apps.yaml: point buildkit_socket at the rootless buildkitd socket and",
    "   replace the frozen test image id (docker image inspect, sha256:...).",
    "3. drawbridge.yaml: tighten allowed_cidrs/allowed_hosts to your segment.",
    "4. Install the compose template and scripts under /etc/drawbridge (see",
    "   docs/DEPLOYMENT.md), then run drawbridge-selfcheck.",
)

